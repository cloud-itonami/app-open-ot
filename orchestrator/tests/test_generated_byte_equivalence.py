"""Byte-equivalence: hand-rolled packers vs codegen output.

For each of the three cells, pack a known engineering-unit value via the
hand-rolled `pack_*` function and via the generated `_generated.<cell>.pack_*`
function, then assert byte-identical output. Catches manifest ⇄ Rust drift
at CI: if the hand-rolled code goes out of sync with the manifest, this
test fires; if the manifest goes out of sync with Rust, the validator + the
existing wasm round-trip tests fire.
"""

from __future__ import annotations

import pytest

from open_ot_orchestrator._generated import (
    anti_islanding_rocof as gen_islanding,
    droop_p_f as gen_droop,
    pid_limited as gen_pid,
)
from open_ot_orchestrator.microgrid_islanding_langgraph import (
    pack_islanding_data_in as hand_islanding_data_in,
    pack_islanding_params as hand_islanding_params,
)
from open_ot_orchestrator.microgrid_pregel import (
    pack_droop_data_in as hand_droop_data_in,
    pack_droop_params as hand_droop_params,
)


# ---------------------------------------------------------------------------
# pid-limited DataIn  (hand-rolled is in pid-limited's own test path; here
# we exercise the format-string equivalence by packing the same i32 values
# directly via struct.pack with DATA_IN_FMT and via the generated dataclass.)
# ---------------------------------------------------------------------------


def test_pid_limited_data_in_round_trip():
    d = gen_pid.DataIn(pv=50_000_000, sp=60_000_000, pv_quality=0, enable=True)
    buf = gen_pid.pack_data_in(d)
    assert len(buf) == gen_pid.DATA_IN_SIZE == 12
    decoded = gen_pid.unpack_data_in(buf)
    assert decoded.pv == 50_000_000
    assert decoded.sp == 60_000_000
    assert decoded.pv_quality == 0
    assert decoded.enable is True


def test_pid_limited_format_constants_match_microgrid_pregel():
    """Hand-rolled DROOP_PARAMS_FMT (in microgrid_pregel) was hand-derived;
    cross-check the equivalent for pid-limited isn't directly imported but
    the generated constant is the SSoT going forward.
    """
    from open_ot_orchestrator import microgrid_pregel as mp
    # microgrid_pregel only ships hand-rolled droop helpers; pid-limited
    # is exercised via the rust+wasm round-trip in test_pregel_runner.
    assert gen_pid.DATA_IN_FMT == "<iiBB2x"
    assert gen_pid.DATA_IN_SIZE == 12
    # The generated droop-p-f constants must match the hand-rolled ones
    # in microgrid_pregel.
    assert gen_droop.DATA_IN_FMT == mp.DROOP_DATA_IN_FMT
    assert gen_droop.DATA_IN_SIZE == mp.DROOP_DATA_IN_SIZE
    assert gen_droop.DATA_OUT_FMT == mp.DROOP_DATA_OUT_FMT
    assert gen_droop.DATA_OUT_SIZE == mp.DROOP_DATA_OUT_SIZE
    assert gen_droop.PARAMS_FMT == mp.DROOP_PARAMS_FMT
    assert gen_droop.PARAMS_SIZE == mp.DROOP_PARAMS_SIZE
    assert gen_droop.INTERNAL_FMT == mp.DROOP_INTERNAL_FMT
    assert gen_droop.INTERNAL_SIZE == mp.DROOP_INTERNAL_SIZE


